"""Write the reproducible synthetic demonstration files."""

from pathlib import Path

from app.demo.generator import frames_to_csv_bytes, generate_demo

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "sample_data" / "demo"


def main() -> None:
    bundle = generate_demo()
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "textbooks").mkdir(exist_ok=True)
    for name, payload in frames_to_csv_bytes(bundle).items():
        (OUT / name).write_bytes(payload)
    for material_id, text in bundle.textbooks.items():
        (OUT / "textbooks" / f"{material_id}.txt").write_text(text, encoding="utf-8")
    (OUT / "README.txt").write_text(
        "SYNTHETIC DATA\n"
        "These files were generated by app.demo.generator.generate_demo(seed=7).\n"
        "They are not real student records and must not be cited as educational evidence.\n"
        f"Rows: {len(bundle.responses)}\n"
        f"Generator: {bundle.meta}\n",
        encoding="utf-8",
    )
    print(f"Wrote {len(bundle.responses)} response rows to {OUT}")


if __name__ == "__main__":
    main()
