"""Load one public synthetic dataset so judges are not looking at an empty database."""

from __future__ import annotations

import logging

from sqlalchemy import select

from app.core.access import set_owner_token
from app.data_ingestion.csv_loader import (
    parse_allocations_csv,
    parse_prerequisites_csv,
    parse_responses_csv,
    parse_topics_csv,
)
from app.data_ingestion.service import ingest_parsed
from app.database.session import get_session_factory
from app.demo.generator import frames_to_csv_bytes, generate_demo
from app.models.entities import Dataset
from app.services.analytics_service import save_material_text

logger = logging.getLogger(__name__)


def seed_public_demo() -> str | None:
    session = get_session_factory()()
    try:
        existing = session.scalar(
            select(Dataset).where(Dataset.source_type == "synthetic_demo", Dataset.visibility == "public")
        )
        if existing is not None:
            return existing.id
        set_owner_token(None)
        bundle = generate_demo(students_per_school_grade=12)
        files = frames_to_csv_bytes(bundle)
        result = ingest_parsed(
            session,
            name="Synthetic mathematics demonstration",
            description="Generated by app.demo.generator. Not real student evidence.",
            responses=parse_responses_csv(files["responses.csv"], "responses.csv"),
            topics=parse_topics_csv(files["topics.csv"]),
            prerequisites=parse_prerequisites_csv(files["prerequisites.csv"]),
            allocations=parse_allocations_csv(files["allocations.csv"]),
            is_synthetic=True,
            source_type="synthetic_demo",
            visibility="public",
            owner_token=None,
        )
        for external_id, text in bundle.textbooks.items():
            save_material_text(
                session,
                result["dataset_id"],
                external_id,
                "Synthetic textbook " + external_id,
                text,
                external_id + ".txt",
                is_synthetic=True,
            )
        logger.info("Seeded public synthetic dataset %s", result["dataset_id"])
        return result["dataset_id"]
    finally:
        session.close()
